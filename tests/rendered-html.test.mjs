  assert.match(html, /id="connect-from-label"/);
  assert.match(html, /id="node-graph-dialog"/);
  assert.match(html, /data-admin-action="graph"/);
  assert.match(html, /id="annotation-panel"/);
  assert.match(app, /N\$\{String\(number\)\.padStart\(3, "0"\)\}/);
  assert.doesNotMatch(app, /beginGraphConnection/);
  assert.match(app, /\/api\/admin\/links\/pair/);
  assert.match(css, /#login-form \.primary-button \{ margin-top: 30px; \}/);
  assert.match(pairRoute, /DB\.batch/);
  assert.doesNotMatch(html, /id="floor-panel"/);
  assert.doesNotMatch(html, /class="scene-card"/);
  assert.doesNotMatch(html, /welcome-photo|dshs-campus/);
  assert.doesNotMatch(html, /MAIN-F02-EAST-N018/);
  assert.doesNotMatch(html, /15070604/);
